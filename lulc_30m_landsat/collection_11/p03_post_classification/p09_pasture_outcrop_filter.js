/**
 * ==============================================================================
 * p09 | Pasture and rocky outcrop adjustment
 * ------------------------------------------------------------------------------
 * SUMMARY
 *   The heaviest post-classification step. It runs its own Random Forest instead
 *   of only correcting the existing map.
 *   
 *   Rocky outcrops (29) are spectrally close to bare soil and exposed pasture, and
 *   the main classifier confuses them. Here a dedicated model is trained per year
 *   on rock-sensitive indices (host rocks, ferrous rocks, Eisen, BSI) and only the
 *   pixels it finds as outcrop in more than ten years are accepted, since rock
 *   does not come and go.
 *   
 *   The rest of the script works on pasture:
 *     - stable pasture persistence: two consecutive pasture years anchor the class
 *       forward, so the model cannot drop in and out of pasture;
 *     - new 2025 pasture below the minimum mapping unit reverts to its 2024 class;
 *     - a trajectory constraint stops long pasture runs from being followed by
 *       forest, which would imply implausibly fast regrowth;
 *     - a slope mask removes pasture and agriculture from steep ground.
 *
 * INPUTS
 *   - PANT_col11_Anual_v36 (from p08)
 *   - Landsat monthly mosaics (mosaicos_mensais_do_Google_v1 module)
 *   - pts_trained_stable_v5_regiao_7_trained
 *   - Hand-drawn outcrop and grassland polygons (imports block)
 *
 * OUTPUTS
 *   - PANT_col11_Anual_v{VERSION_OUT} (one band per year, 1985-2025)
 *
 * NOTES
 *   - The imports block carries the hand-drawn geometries this script depends on
 *     (aflora, campestre, agua_para_savana, agua_para_nao_veg, geometry2).
 *   - Set IS_COLETA to true to run a single year while collecting samples.
 *
 * PIPELINE
 *   p03 post-classification | step 9 of 9  ->  p10_suspicious_patches
 * ==============================================================================
 */

